"""How far a running analysis has got, for a progress display that is true.

An analysis is one HTTP request that can take a minute when imagery is
fetched. The browser cannot see inside it, so it sends a random
``client_ref`` with the request and polls ``GET /api/progress/{client_ref}``
while it waits. The pipeline reports each stage as it finishes, and the
fetcher reports its own steps -- finding the place, searching, downloading.

Entries are tiny, bounded in number, and readable only by the user who
started the run.
"""

from __future__ import annotations

import re
import threading
import time
from collections import OrderedDict

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel

from app.api.auth import current_user
from app.auth import User

#: Generated by the browser; constrained because it arrives in a URL.
CLIENT_REF = re.compile(r"^[A-Za-z0-9_-]{8,64}$")
CAPACITY = 500


class ProgressOut(BaseModel):
    #: The pipeline stage last reported: ``understanding``, ``acquisition``, ...
    stage: str
    #: ``running`` while a stage is under way, otherwise how it ended.
    status: str
    detail: str = ""
    done: bool = False


class ProgressStore:
    def __init__(self, capacity: int = CAPACITY) -> None:
        self._entries: OrderedDict[str, tuple[str | None, ProgressOut, float]] = OrderedDict()
        self._capacity = capacity
        self._lock = threading.Lock()

    def report(
        self,
        ref: str,
        user_id: str | None,
        stage: str,
        status: str,
        detail: str = "",
        done: bool = False,
    ) -> None:
        entry = ProgressOut(stage=stage, status=status, detail=detail[:300], done=done)
        with self._lock:
            self._entries[ref] = (user_id, entry, time.time())
            self._entries.move_to_end(ref)
            while len(self._entries) > self._capacity:
                self._entries.popitem(last=False)

    def get(self, ref: str, user_id: str | None) -> ProgressOut | None:
        with self._lock:
            found = self._entries.get(ref)
        if found is None or found[0] != user_id:
            return None
        return found[1]


progress_store = ProgressStore()

router = APIRouter(prefix="/api/progress", tags=["analysis"])


@router.get("/{client_ref}", response_model=ProgressOut)
def get_progress(client_ref: str, user: User | None = Depends(current_user)) -> ProgressOut:
    """The last stage a running analysis reported."""
    entry = progress_store.get(client_ref, user.id if user else None) if CLIENT_REF.match(client_ref) else None
    if entry is None:
        raise HTTPException(404, "No analysis is reporting progress under that reference.")
    return entry


__all__ = ["CLIENT_REF", "ProgressOut", "ProgressStore", "progress_store", "router"]
